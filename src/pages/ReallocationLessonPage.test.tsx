it('synchronizes cross-tab state and clearing, then permits an explicit restart', () => {
  renderPage()
  window.localStorage.setItem(PROGRESS_STORAGE_KEY, JSON.stringify({ version: 2, lastVisitedLessonId: 'memory-reallocation', lessons: {
    'memory-reallocation': { guidedRunCompleted: true, completedChallengeIds: [], savedState: { dataset: 'zeros', outcome: 'failure', requested: 1, fill: 0 } },
  } }))
  act(() => window.dispatchEvent(new StorageEvent('storage', { key: PROGRESS_STORAGE_KEY })))
  expect(screen.getByRole('combobox', { name: '原始資料' })).toHaveValue('zeros')
  finish(); expect(outputs()).toEqual(['resize failed; original kept', 'count=3, sum=0'])
  act(() => { window.localStorage.removeItem(PROGRESS_STORAGE_KEY); window.dispatchEvent(new StorageEvent('storage', { key: PROGRESS_STORAGE_KEY })) })
  expect(screen.queryByRole('button', { name: /執行下一步/ })).not.toBeInTheDocument()
  expect(window.localStorage.getItem(PROGRESS_STORAGE_KEY)).toBeNull()
  predict(); finish()
  expect(loadProgress().lastVisitedLessonId).toBe('memory-reallocation')
  expect(loadProgress().lessons['memory-reallocation']?.guidedRunCompleted).toBe(true)
})
it('recovers malformed saved settings without dropping an earlier allocation lesson', () => {
  const previous = { guidedRunCompleted: true, completedChallengeIds: ['predict-allocated-sum'], savedState: { allocator: 'calloc', outcome: 'failure', count: 5, start: 20 } }
  window.localStorage.setItem(PROGRESS_STORAGE_KEY, JSON.stringify({ version: 2, lastVisitedLessonId: 'memory-reallocation', lessons: {
    'memory-allocation': previous,
    'memory-reallocation': { guidedRunCompleted: true, completedChallengeIds: [], savedState: { dataset: 'mixed', outcome: { toString: null }, requested: 5, fill: 6 } },
  } }))
  expect(loadProgress().lessons['memory-allocation']).toEqual(previous)
  expect(loadProgress().lessons['memory-reallocation']).toMatchObject({ guidedRunCompleted: false, savedState: { dataset: 'mixed', outcome: 'moved', requested: 5, fill: 6 } })
  expect(isReallocationSavedState({ dataset: 'descending', outcome: 'in-place', requested: 1, fill: 0 })).toBe(true)
  for (const value of [null, [], { dataset: 'constructor', outcome: 'moved', requested: 5, fill: 6 }, { dataset: 'mixed', outcome: 'failure', requested: 0, fill: 6 }, { dataset: 'mixed', outcome: 'failure', requested: 1, fill: '6' }]) expect(isReallocationSavedState(value)).toBe(false)
})
