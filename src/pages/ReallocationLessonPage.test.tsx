import { StrictMode } from 'react'
import { act, fireEvent, render, screen, within } from '@testing-library/react'
import { HashRouter, MemoryRouter } from 'react-router-dom'
import App from '../App'
import { ProgressProvider } from '../hooks/useLearningProgress'
import { getCourseProgress, isReallocationSavedState, loadProgress, PROGRESS_STORAGE_KEY } from '../state'
import { ReallocationLessonPage } from './ReallocationLessonPage'

const renderPage = () => render(<StrictMode><ProgressProvider><MemoryRouter><ReallocationLessonPage /></MemoryRouter></ProgressProvider></StrictMode>)
const nextButton = () => screen.getByRole<HTMLButtonElement>('button', { name: '容量調整執行：執行下一步' })
function advanceUntil(condition: () => boolean) {
  const button = nextButton()
  for (let i = 0; i < 70; i++) { if (condition()) return; if (button.disabled) break; fireEvent.click(button) }
  throw new Error('Expected reallocation phase not reached')
}
function finish() { const button = nextButton(); advanceUntil(() => button.disabled) }
const phase = (value: string) => document.querySelector(`.allocation-execution[data-phase="${value}"]`) !== null
const activeLine = (line: number) => document.querySelector(`.source-code-panel__line.is-active[data-line="${line}"]`) !== null
function predict(value = '5 32') { fireEvent.change(screen.getByRole('textbox', { name: '預測有效容量、總和' }), { target: { value } }); fireEvent.click(screen.getByRole('button', { name: '提交預測' })) }
const choose = (name: string, value: string) => fireEvent.change(screen.getByRole('combobox', { name }), { target: { value } })
const slide = (name: string, value: number) => fireEvent.change(screen.getByRole('slider', { name }), { target: { value: String(value) } })
const outputs = () => within(screen.getByRole('list', { name: '容量調整輸出' })).queryAllByRole('listitem').map(item => item.textContent)
beforeEach(() => window.localStorage.clear())

it('preserves the initialized prefix and initializes new cells before reading them', () => {
  renderPage()
  expect(screen.queryByRole('button', { name: /執行下一步/ })).not.toBeInTheDocument()
  expect(screen.queryByLabelText('A[0]')).not.toBeInTheDocument()
  predict('5'); expect(screen.getByRole('alert')).toHaveTextContent('兩個非負整數')
  predict(); advanceUntil(() => phase('set-requested'))
  expect(screen.getByLabelText('A[0]')).toHaveTextContent('4')
  expect(screen.getByLabelText('A[1]')).toHaveTextContent('7')
  expect(screen.getByLabelText('A[2]')).toHaveTextContent('9')
  fireEvent.click(nextButton()); expect(activeLine(14)).toBe(true)
  expect(screen.getByLabelText('p 指向')).toHaveTextContent('失效（不可讀取）')
  expect(screen.getByLabelText('tmp 指向')).toHaveTextContent('結果區塊 B')
  expect(screen.getByLabelText('A[0]')).toHaveTextContent('不可存取')
  expect(screen.getByLabelText('B[0]')).toHaveTextContent('4')
  expect(screen.getByLabelText('B[3]')).toHaveTextContent('未初始化')
  expect(screen.getByLabelText('B[4]')).toHaveTextContent('未初始化')
  expect(screen.getByLabelText('目前 count')).toHaveTextContent('3')
  advanceUntil(() => phase('adopt-result'))
  expect(screen.getByLabelText('p 指向')).toHaveTextContent('結果區塊 B')
  advanceUntil(() => phase('initialize-new'))
  expect(screen.getByLabelText('B[3]')).toHaveTextContent('6')
  expect(screen.getByLabelText('B[4]')).toHaveTextContent('未初始化')
  advanceUntil(() => phase('update-count'))
  expect(screen.getByLabelText('目前 count')).toHaveTextContent('5')
  const index = screen.getByLabelText('目前 i')
  advanceUntil(() => phase('sum-for-condition') && index.textContent === '5')
  expect(outputs()).toEqual([])
  expect(screen.queryByText(/實際 5、32/)).not.toBeInTheDocument()
  fireEvent.click(nextButton())
  expect(screen.getByText('你預測 5、32，實際 5、32。預測正確！')).toBeInTheDocument()
  expect(outputs()).toEqual(['count=5, sum=32'])
  finish()
  expect(loadProgress().lessons['memory-reallocation']?.guidedRunCompleted).toBe(true)
})
it('treats an unchanged position as a new lifetime and adopts the returned pointer', () => {
  renderPage(); choose('realloc 結果（模擬情境）', 'in-place'); predict(); advanceUntil(() => phase('reallocate'))
  expect(screen.getByLabelText('區塊 A')).toHaveTextContent('模擬位置 X')
  expect(screen.getByLabelText('區塊 B')).toHaveTextContent('模擬位置 X')
  expect(screen.getByLabelText('區塊 A 狀態')).toHaveTextContent('已由 realloc 結束生命週期')
  expect(screen.getByLabelText('p 指向')).toHaveTextContent('失效（不可讀取）')
  expect(screen.getByLabelText('tmp 指向')).toHaveTextContent('結果區塊 B')
  advanceUntil(() => phase('adopt-result')); expect(screen.getByLabelText('p 指向')).toHaveTextContent('結果區塊 B')
  finish(); expect(outputs()).toEqual(['count=5, sum=32'])
})
it.each([1, 5])('keeps count = 3 and original data on failure when requesting %i elements', requested => {
  renderPage(); choose('realloc 結果（模擬情境）', 'failure'); slide('目標容量 requested', requested)
  expect(screen.getByRole('slider', { name: '新增元素值' })).toBeDisabled()
  predict('3 20'); advanceUntil(() => phase('reallocate'))
  expect(screen.getByLabelText('p 指向')).toHaveTextContent('原區塊 A')
  expect(screen.getByLabelText('tmp 指向')).toHaveTextContent('NULL')
  expect(screen.getByLabelText('區塊 A 狀態')).toHaveTextContent('有效')
  expect(screen.getByLabelText('區塊 B 狀態')).toHaveTextContent('尚未建立')
  expect(screen.getByLabelText('目前 count')).toHaveTextContent('3')
  advanceUntil(() => phase('print-failure'))
  expect(outputs()).toEqual(['resize failed; original kept'])
  expect(screen.queryByText(/實際 3、20/)).not.toBeInTheDocument()
  finish()
  expect(outputs()).toEqual(['resize failed; original kept', 'count=3, sum=20'])
  expect(screen.getByLabelText('區塊 A 狀態')).toHaveTextContent('已由 free 釋放')
  expect(loadProgress().lessons['memory-reallocation']?.guidedRunCompleted).toBe(true)
})
it('shrinks the readable range without running the initialization body or touching the removed tail', () => {
  renderPage(); slide('目標容量 requested', 2); predict('2 11'); advanceUntil(() => phase('new-for-condition'))
  expect(screen.getByLabelText('目前判斷')).toHaveTextContent('3 < 2 → 不成立')
  expect(screen.queryByLabelText('B[2]')).not.toBeInTheDocument()
  expect(screen.getByLabelText('A[2]')).toHaveTextContent('不可存取')
  expect(screen.getByLabelText('目前 count')).toHaveTextContent('3')
  fireEvent.click(nextButton()); expect(phase('update-count')).toBe(true)
  expect(screen.getByLabelText('目前 count')).toHaveTextContent('2')
  advanceUntil(() => phase('sum-for-init')); expect(screen.getByLabelText('目前 i')).toHaveTextContent('0')
  finish(); expect(outputs()).toEqual(['count=2, sum=11'])
})
it('handles unchanged capacity and clears both aliases after a single free', () => {
  renderPage(); slide('目標容量 requested', 3); predict('3 20'); advanceUntil(() => phase('new-for-condition'))
  expect(screen.getByLabelText('目前判斷')).toHaveTextContent('3 < 3 → 不成立')
  advanceUntil(() => phase('free'))
  expect(screen.getByLabelText('p 指向')).toHaveTextContent('失效（不可讀取）')
  expect(screen.getByLabelText('tmp 指向')).toHaveTextContent('失效（不可讀取）')
  for (const index of [0, 1, 2]) expect(screen.getByLabelText(`B[${index}]`)).toHaveTextContent('不可存取')
  fireEvent.click(nextButton()); expect(screen.getByLabelText('p 指向')).toHaveTextContent('NULL')
  expect(screen.getByLabelText('tmp 指向')).toHaveTextContent('失效（不可讀取）')
  fireEvent.click(nextButton()); expect(screen.getByLabelText('tmp 指向')).toHaveTextContent('NULL')
  finish()
  expect(screen.getByLabelText('p 指向')).toHaveTextContent('—')
  expect(screen.getByLabelText('目前 count')).toHaveTextContent('—')
  expect(outputs()).toEqual(['count=3, sum=20'])
})
it('supports zero-valued growth, resets changed settings and reports an incorrect prediction', () => {
  renderPage(); choose('原始資料', 'zeros'); slide('新增元素值', 0); slide('目標容量 requested', 4)
  predict('4 1'); finish()
  expect(outputs()).toEqual(['count=4, sum=0'])
  expect(screen.getByText(/你預測 4、1，實際 4、0/)).toHaveTextContent('先確認調整是否成功')
  fireEvent.click(screen.getByRole('button', { name: '恢復預設值' }))
  expect(phase('prepare')).toBe(true)
  expect(outputs()).toEqual([])
  expect(screen.getByRole('textbox', { name: '預測有效容量、總和' })).toHaveValue('')
  expect(screen.getByRole('combobox', { name: '原始資料' })).toHaveValue('mixed')
  predict(); finish(); expect(outputs()).toEqual(['count=5, sum=32'])
})
it('cancels a playing trace when a setting changes', () => {
  vi.useFakeTimers()
  try {
    const view = renderPage(); predict()
    fireEvent.click(screen.getByRole('button', { name: '容量調整執行：2 倍速' }))
    fireEvent.click(screen.getByRole('button', { name: '容量調整執行：開始播放' }))
    act(() => vi.advanceTimersByTime(380)); expect(phase('enter-main')).toBe(true)
    fireEvent.click(screen.getByRole('button', { name: '容量調整執行：暫停播放' }))
    act(() => vi.advanceTimersByTime(1000)); expect(phase('enter-main')).toBe(true)
    fireEvent.click(screen.getByRole('button', { name: '容量調整執行：開始播放' }))
    choose('realloc 結果（模擬情境）', 'failure')
    act(() => vi.advanceTimersByTime(10000))
    expect(phase('prepare')).toBe(true)
    expect(screen.queryByRole('button', { name: /執行下一步/ })).not.toBeInTheDocument()
    expect(loadProgress().lessons['memory-reallocation']?.guidedRunCompleted).toBe(false)
    view.unmount()
  } finally { vi.useRealTimers() }
})
